import assert from 'node:assert/strict';
import path from 'node:path';
import { assertTheme } from './theme-browser.mjs';

export async function verifyPlannerWorkspace({ page, navigate, act, snapshot, providerRequests, noOverflow, record, outputDirectory }) {
  const requests = providerRequests.length;
  await navigate('Work');
  assert.equal(await page.getByRole('button', { name: 'Planner', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.getByLabel('Planner date', { exact: true }).fill('2026-10-12');
  await page.getByRole('button', { name: 'Templates', exact: true }).click();
  await page.getByRole('button', { name: '＋ New template', exact: true }).click();
  await page.getByLabel('Template name', { exact: true }).fill('Synthetic daily ritual');
  await page.getByLabel('Template repeat', { exact: true }).selectOption('daily');
  await page.getByLabel('Task 1', { exact: true }).fill('Synthetic morning journal');
  await page.getByRole('button', { name: '＋ Add template task', exact: true }).click();
  await page.getByLabel('Section / project 2', { exact: true }).fill('Arkive project');
  await page.getByLabel('Task 2', { exact: true }).fill('Synthetic design review');
  const template = await act('/v1/workspace/templates', 'POST', () => page.getByRole('button', { name: 'Save template', exact: true }).click());
  assert.equal(template.repeat, 'daily');
  assert.equal((await snapshot()).workspace.tasks.filter(task => task.templateId === template.id).length, 0);
  await act('/v1/workspace/planner/day', 'POST', () => page.getByRole('button', { name: 'Planner', exact: true }).click());
  assert.equal((await snapshot()).workspace.tasks.filter(task => task.templateId === template.id).length, 2);
  const journal = page.locator('.pn-planner-sheet .pn-wp-task').filter({ hasText: 'Synthetic morning journal' });
  await act('/v1/workspace/tasks', 'POST', () => journal.getByRole('checkbox').click());
  assert.equal(await journal.getByRole('checkbox').isChecked(), true);
  await page.getByRole('group', { name: 'Daily sections' }).getByRole('button', { name: /Arkive project/ }).click();
  await page.getByRole('heading', { name: 'Synthetic design review', exact: true }).waitFor();
  await act('/v1/workspace/planner/day', 'POST', () => page.getByRole('button', { name: 'Next day', exact: true }).click());
  const state = await snapshot();
  assert.equal(state.workspace.tasks.filter(task => task.templateId === template.id).length, 4);
  assert.equal(state.workspace.tasks.filter(task => task.dueDate === '2026-10-13').every(task => task.status === 'todo'), true);
  await page.getByRole('button', { name: 'Previous day', exact: true }).click();
  await page.getByRole('group', { name: 'Daily sections' }).getByRole('button', { name: /Personal/ }).click();
  assert.equal(await journal.getByRole('checkbox').isChecked(), true);
  assert.equal((await snapshot()).workspace.tasks.filter(task => task.templateId === template.id).length, 4);
  await noOverflow('desktop dated planner');
  await page.screenshot({ path: path.join(outputDirectory, 'planner-daily-desktop.png'), animations: 'disabled' });
  await page.getByRole('button', { name: 'Calendar', exact: true }).click();
  assert.equal(await page.locator('.pn-calendar-grid button').count(), 42);
  assert.ok((await page.locator('.pn-calendar-grid').textContent()).includes('+2 planned'));
  await assertTheme(page, '.pn-work-cabinet', 'background-color', '--pn-panel');
  await assertTheme(page, '.pn-calendar', 'background-color', '--pn-raised');
  await assertTheme(page, '.pn-calendar-grid button[aria-pressed=true]', 'background-color', '--pn-accent');
  record('Work and Calendar use the shared app surfaces and action accent');
  await noOverflow('desktop task calendar');
  await page.screenshot({ path: path.join(outputDirectory, 'planner-calendar-desktop.png'), animations: 'disabled' });
  record('Daily templates generate once per date; separate section tabs, completion history and calendar forecasts are real');

  await page.getByRole('button', { name: 'Templates', exact: true }).click();
  await page.getByRole('button', { name: 'Edit template Synthetic daily ritual', exact: true }).click();
  await page.getByLabel('Task 1', { exact: true }).fill('Synthetic revised journal');
  await page.getByRole('checkbox', { name: 'Enable automatic recurrence', exact: true }).uncheck();
  await act('/v1/workspace/templates', 'POST', () => page.getByRole('button', { name: 'Save template', exact: true }).click());
  await page.getByLabel('Planner date', { exact: true }).fill('2026-10-14');
  await act('/v1/workspace/planner/day', 'POST', () => page.getByRole('button', { name: 'Use on 2026-10-14', exact: true }).click());
  assert.equal((await snapshot()).workspace.tasks.find(task => task.templateId === template.id && task.templateDate === '2026-10-12').title, 'Synthetic morning journal');
  assert.equal((await snapshot()).workspace.tasks.find(task => task.templateId === template.id && task.templateDate === '2026-10-14').title, 'Synthetic revised journal');
  await page.getByRole('button', { name: '＋ New task', exact: true }).click();
  await page.getByLabel('Task title', { exact: true }).fill('Synthetic scheduled one-off');
  assert.equal(await page.getByLabel('Scheduled date', { exact: true }).inputValue(), '2026-10-14');
  await page.getByLabel('Section / project', { exact: true }).fill('Client project');
  const oneOff = await act('/v1/workspace/tasks', 'POST', () => page.getByRole('button', { name: 'Save task', exact: true }).click());
  assert.equal(oneOff.dueDate, '2026-10-14'); assert.equal(oneOff.section, 'Client project');
  await page.getByRole('group', { name: 'Daily sections' }).getByRole('button', { name: /Client project/ }).click();
  await page.getByRole('button', { name: 'Edit task Synthetic scheduled one-off', exact: true }).click();
  await page.getByLabel('Scheduled date', { exact: true }).fill('2026-10-16');
  await act('/v1/workspace/tasks', 'POST', () => page.getByRole('button', { name: 'Save task', exact: true }).click());
  assert.equal((await snapshot()).workspace.tasks.find(task => task.id === oneOff.id).dueDate, '2026-10-16');
  assert.equal((await snapshot()).workspace.tasks.find(task => task.title === 'Synthetic review task').dueDate, undefined);
  record('Template edits preserve prior days; manual application, project grouping, individual rescheduling and legacy undated tasks verified');
  const viewport = page.viewportSize();
  await page.getByRole('button', { name: 'Calendar', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await noOverflow('mobile task calendar');
  await page.locator('.pn-calendar').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(outputDirectory, 'planner-calendar-mobile.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 320, height: 844 });
  await noOverflow('320px task calendar');
  await page.getByRole('button', { name: 'Templates', exact: true }).click();
  await page.getByRole('button', { name: 'Edit template Synthetic daily ritual', exact: true }).click();
  await noOverflow('320px template editor');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.setViewportSize(viewport);
  assert.equal(providerRequests.length, requests);
  record('Planner calendar and template editor are mobile-safe and cause no model requests');
}
