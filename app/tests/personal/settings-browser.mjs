import assert from 'node:assert/strict';
import path from 'node:path';
import { assertTheme } from './theme-browser.mjs';

export async function verifySettings({ page, act, snapshot, navigate, providerRequests, outputDirectory, record, noOverflow }) {
  const before = await snapshot(); const count = providerRequests.length;
  await navigate('Settings');
  const settings = page.getByRole('region', { name: 'Arkive settings', exact: true });
  await settings.getByLabel('API base URL', { exact: true }).waitFor();
  await assertTheme(page, '.pn-settings-nav', 'background-color', '--pn-panel');
  await assertTheme(page, '.pn-settings-card', 'background-color', '--pn-raised');
  await assertTheme(page, '.pn-settings-nav [aria-current=page]', 'background-color', '--pn-selected');
  record('Settings surfaces and selections match the shared Arkive palette');
  assert.equal(await settings.getByRole('button', { name: 'Save connection', exact: true }).isEnabled(), false);
  assert.equal(providerRequests.length, count);
  const key = 'synthetic-browser-settings-key';
  await settings.getByLabel('API key (optional for local servers)', { exact: true }).fill(key);
  await settings.getByLabel('Temperature (optional)', { exact: true }).fill('0.4');
  await settings.getByLabel('Max output tokens (optional)', { exact: true }).fill('1200');
  await settings.getByRole('checkbox', { name: /Save this connection/ }).check();
  const saved = await act('/v1/settings/provider', 'POST', () => settings.getByRole('button', { name: 'Save connection', exact: true }).click());
  assert.equal(saved.hasApiKey, true); assert.equal(saved.apiKey, undefined);
  assert.equal(await settings.getByLabel('Replace API key (optional)', { exact: true }).inputValue(), '');
  assert.equal(providerRequests.length, count, 'Save must not send a model request');
  assert.deepEqual((await snapshot()).rooms, before.rooms);
  assert.deepEqual((await snapshot()).objects, before.objects);
  const storage = await page.evaluate(() => ({ ...localStorage, ...sessionStorage }));
  assert.ok(!JSON.stringify(storage).includes(key));
  record('settings save is explicit, credentials redacted, no source/permission/model mutation');
  await settings.getByRole('checkbox', { name: /Allow a model-list request/ }).check();
  const checked = await act('/v1/settings/provider/check', 'POST', () => settings.getByRole('button', { name: 'Check saved connection', exact: true }).click());
  assert.equal(checked.modelListed, true); assert.equal(checked.completionVerified, false);
  assert.equal(providerRequests.length, count);
  await settings.getByText(/Model list reachable/).waitFor();
  record('explicit model-list check reports metadata reachability, not chat verification');
  await page.screenshot({ path: path.join(outputDirectory, 'settings-models-desktop.png'), fullPage: false });
  const nav = settings.getByRole('navigation', { name: 'Settings sections' });
  await nav.getByRole('button', { name: 'Agents & harnesses' }).click();
  await settings.getByText('External agent harnesses', { exact: true }).waitFor();
  assert.equal(await settings.getByRole('button', { name: /Launch|Install|Run harness/ }).count(), 0);
  await nav.getByRole('button', { name: 'Nodes, sync & recovery' }).click();
  await settings.getByRole('heading', { name: 'Connected node', exact: true }).waitFor();
  await nav.getByRole('button', { name: 'Appearance & shortcuts' }).click();
  await settings.getByLabel('Animations', { exact: true }).selectOption('reduced');
  assert.equal(await page.evaluate(() => document.documentElement.dataset.arkiveMotion), 'reduced');
  await settings.getByLabel('Animations', { exact: true }).selectOption('system');
  await nav.getByRole('button', { name: 'Channels & availability' }).click();
  await settings.getByRole('heading', { name: 'Not connected yet', exact: true }).waitFor();
  record('settings categories preserve node controls and distinguish unavailable integrations');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await nav.getByRole('button', { name: 'Models & connections' }).click();
    await settings.getByLabel('Replace API key (optional)', { exact: true }).waitFor();
    assert.equal(await settings.getByLabel('Temperature (optional)', { exact: true }).inputValue(), '0.4');
    await noOverflow(`settings ${width}px`);
    await page.screenshot({ path: path.join(outputDirectory, `settings-models-${width}.png`), fullPage: false });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  const connections = settings.getByRole('region', { name: 'Saved model connections' });
  const endpoint = await settings.getByLabel('API base URL', { exact: true }).inputValue();
  const model = await settings.getByLabel('Model ID', { exact: true }).inputValue();
  await connections.getByRole('button', { name: '＋ Add connection', exact: true }).click();
  await connections.getByLabel('Connection name', { exact: true }).fill('Secondary test connection');
  await connections.getByLabel('Connection API base URL', { exact: true }).fill(endpoint);
  await connections.getByLabel('Connection model ID', { exact: true }).fill(model);
  await connections.getByRole('checkbox', { name: /Save this named connection/ }).check();
  const registry = await act('/v1/settings/connections', 'POST', () => connections.getByRole('button', { name: 'Save named connection', exact: true }).click());
  assert.equal(registry.activeId, 'default');
  const secondary = registry.connections.find(item => item.name === 'Secondary test connection');
  assert.equal(secondary.hasApiKey, false);
  await connections.getByLabel('Saved model connection', { exact: true }).selectOption(secondary.id);
  assert.equal(await connections.getByRole('button', { name: 'Use as node default' }).isEnabled(), false);
  await connections.getByRole('checkbox', { name: /Confirm changing the node default/ }).check();
  await act('/v1/settings/connections', 'POST', () => connections.getByRole('button', { name: 'Use as node default' }).click());
  await settings.getByLabel('API key (optional for local servers)', { exact: true }).waitFor();
  assert.equal(providerRequests.length, count);
  await nav.getByRole('button', { name: 'Runtime & safety' }).click();
  await settings.getByText('Opt-in per request: up to 8 completed turns / 32,000 characters with identical source, permission and connection boundaries', { exact: true }).waitFor();
  await settings.getByRole('heading', { name: 'Hermes', exact: true }).waitFor();
  await page.screenshot({ path: path.join(outputDirectory, 'settings-runtime-desktop.png'), fullPage: false });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await noOverflow(`runtime settings ${width}px`);
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await nav.getByRole('button', { name: 'Models & connections' }).click();
  await connections.getByLabel('Saved model connection', { exact: true }).selectOption('default');
  await connections.getByRole('checkbox', { name: /Confirm changing the node default/ }).check();
  await act('/v1/settings/connections', 'POST', () => connections.getByRole('button', { name: 'Use as node default' }).click());
  await settings.getByLabel('Replace API key (optional)', { exact: true }).waitFor();
  assert.equal(providerRequests.length, count);
  assert.deepEqual((await snapshot()).rooms, before.rooms);
  record('named connections remain separate, activation is explicit and sends no model request');
  record('runtime settings show effective route and unavailable harnesses at desktop and mobile widths');
  await navigate('Chat'); await page.keyboard.press('Control+,');
  await page.getByRole('region', { name: 'Arkive settings', exact: true }).waitFor();
  record('settings shortcut opens real saved connection without model execution');
}
