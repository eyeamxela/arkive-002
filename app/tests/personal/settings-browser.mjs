import assert from 'node:assert/strict';
import path from 'node:path';
import { assertTheme } from './theme-browser.mjs';
import { verifyModelReliability } from './model-reliability-browser.mjs';

export async function verifySettings({ page, act, snapshot, navigate, providerRequests, outputDirectory, record, noOverflow }) {
  const before = await snapshot(); const count = providerRequests.length;
  await navigate('Settings');
  const settings = page.getByRole('region', { name: 'Arkive settings', exact: true });
  const models = settings.getByRole('region', { name: 'Model settings', exact: true });
  const nav = settings.getByRole('navigation', { name: 'Settings sections' });
  await models.getByLabel('Provider', { exact: true }).waitFor();
  await assertTheme(page, '.pn-settings-nav', 'background-color', '--pn-panel');
  await assertTheme(page, '.pn-settings-card', 'background-color', '--pn-raised');
  await assertTheme(page, '.pn-settings-nav [aria-current=page]', 'background-color', '--pn-selected');
  record('Settings surfaces and selections match the shared Arkive palette');
  assert.equal(await models.getByLabel('API key', { exact: true }).count(), 0);
  await models.getByRole('button', { name: 'Edit connection', exact: true }).click();
  const endpoint = await models.getByLabel('API base URL', { exact: true }).inputValue();
  const key = 'synthetic-browser-settings-key';
  await models.getByLabel('API key', { exact: true }).fill(key);
  await models.getByText('Advanced', { exact: true }).click();
  await models.getByLabel('Temperature', { exact: true }).fill('0.4');
  await models.getByLabel('Max output tokens', { exact: true }).fill('1200');
  const saved = await act('/v1/settings/provider', 'POST', () => models.getByRole('button', { name: 'Save connection', exact: true }).click());
  assert.equal(saved.hasApiKey, true); assert.equal(saved.apiKey, undefined);
  await models.getByLabel('Provider', { exact: true }).waitFor();
  assert.equal(await models.getByRole('button', { name: 'Apply', exact: true }).isEnabled(), false);
  assert.ok(!JSON.stringify(await page.evaluate(() => ({ ...localStorage, ...sessionStorage }))).includes(key));
  assert.equal(providerRequests.length, count);
  assert.deepEqual((await snapshot()).rooms, before.rooms); assert.deepEqual((await snapshot()).objects, before.objects);
  record('simple connection save is explicit, encrypted and makes no model or Brain mutation');
  const checked = await act('/v1/settings/provider/check', 'POST', () => models.getByRole('button', { name: 'Load models', exact: true }).click());
  assert.equal(checked.modelListed, true); assert.equal(checked.completionVerified, false);
  await models.getByText(/1 models found/).waitFor();
  record('one-click model discovery sends metadata only and does not test generation');
  await page.screenshot({ path: path.join(outputDirectory, 'settings-models-desktop.png'), fullPage: false });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 }); await noOverflow('settings ' + width + 'px');
    await page.screenshot({ path: path.join(outputDirectory, 'settings-models-' + width + '.png'), fullPage: false });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await models.getByRole('button', { name: '＋ Add provider', exact: true }).click();
  await models.getByLabel('Provider type', { exact: true }).selectOption('openai');
  assert.equal(await models.getByRole('button', { name: 'Load models', exact: true }).isEnabled(), false);
  await models.getByLabel('API key', { exact: true }).fill('synthetic-unsaved-key');
  await models.getByLabel('Model', { exact: true }).selectOption('custom');
  await models.getByLabel('Model ID', { exact: true }).fill('old-provider-model');
  await models.getByLabel('Provider type', { exact: true }).selectOption('custom');
  assert.equal(await models.getByLabel('API key', { exact: true }).inputValue(), '');
  assert.equal(await models.getByLabel('Model', { exact: true }).inputValue(), '');
  await models.getByLabel('API base URL', { exact: true }).fill(endpoint);
  await models.getByLabel('Connection name', { exact: true }).fill('Secondary test connection');
  assert.equal(await models.getByRole('button', { name: 'Save connection', exact: true }).isEnabled(), false);
  const discovered = await act('/v1/settings/provider/check', 'POST', () => models.getByRole('button', { name: 'Load models', exact: true }).click());
  assert.equal(discovered.completionVerified, false);
  await models.getByLabel('Model', { exact: true }).selectOption('model:synthetic-browser-model');
  await page.screenshot({ path: path.join(outputDirectory, 'settings-add-provider-desktop.png'), fullPage: false });
  for (const width of [390, 320]) { await page.setViewportSize({ width, height: 844 }); await noOverflow('add provider ' + width + 'px'); }
  await page.setViewportSize({ width: 1440, height: 1000 });
  const registry = await act('/v1/settings/connections', 'POST', () => models.getByRole('button', { name: 'Save connection', exact: true }).click());
  const secondary = registry.connections.find(c => c.name === 'Secondary test connection');
  assert.equal(secondary.hasApiKey, false); assert.equal(registry.activeId, 'default');
  await models.getByLabel('Provider', { exact: true }).waitFor();
  assert.equal(await models.getByLabel('Provider', { exact: true }).inputValue(), secondary.id);
  await act('/v1/settings/connections', 'POST', () => models.getByRole('button', { name: 'Apply', exact: true }).click());
  assert.equal(providerRequests.length, count);
  record('provider setup discovers before saving; changing providers clears key and model; Apply alone changes default');
  await nav.getByRole('button', { name: 'Agents & harnesses' }).click();
  await settings.getByText('External agent harnesses', { exact: true }).waitFor();
  assert.equal(await settings.getByRole('button', { name: /Launch|Install|Run harness/ }).count(), 0);
  await nav.getByRole('button', { name: 'Nodes, sync & recovery' }).click();
  await settings.getByRole('heading', { name: 'Connected node', exact: true }).waitFor();
  await nav.getByRole('button', { name: 'Appearance & shortcuts' }).click();
  await settings.getByLabel('Animations', { exact: true }).selectOption('reduced');
  assert.equal(await page.evaluate(() => document.documentElement.dataset.arkiveMotion), 'reduced');
  await settings.getByLabel('Animations', { exact: true }).selectOption('system');
  await nav.getByRole('button', { name: 'Connections & channels' }).click();
  await settings.getByRole('region', { name: 'Channel connections', exact: true }).waitFor();
  await settings.getByRole('heading', { name: 'Connect Hermes management', exact: true }).waitFor();
  record('settings categories preserve node controls and expose the Hermes channel browser');
  await nav.getByRole('button', { name: 'Runtime & safety' }).click();
  await settings.getByText('Opt-in per request: up to 8 completed turns / 32,000 characters with identical source, permission and connection boundaries', { exact: true }).waitFor();
  await settings.getByRole('heading', { name: 'Hermes (owner pilot)', exact: true }).waitFor();
  await page.screenshot({ path: path.join(outputDirectory, 'settings-runtime-desktop.png'), fullPage: false });
  for (const width of [390, 320]) { await page.setViewportSize({ width, height: 844 }); await noOverflow('runtime settings ' + width + 'px'); }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await nav.getByRole('button', { name: 'Models & connections' }).click();
  await models.getByLabel('Provider', { exact: true }).selectOption('default');
  await act('/v1/settings/connections', 'POST', () => models.getByRole('button', { name: 'Apply', exact: true }).click());
  await models.getByRole('button', { name: 'Edit connection', exact: true }).click();
  assert.equal(await models.getByLabel('API key (leave blank to keep saved key)', { exact: true }).inputValue(), '');
  await models.getByText('Advanced', { exact: true }).click();
  assert.equal(await models.getByLabel('Temperature', { exact: true }).inputValue(), '0.4');
  await models.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(providerRequests.length, count); assert.deepEqual((await snapshot()).rooms, before.rooms);
  record('named connections retain keys and generation settings independently; cancellation makes no changes');
  record('runtime settings show effective route and unavailable harnesses at desktop and mobile widths');
  await verifyModelReliability({ page, models, act, record, providerRequests });
  await navigate('Chat'); await page.keyboard.press('Control+,');
  await models.getByLabel('Provider', { exact: true }).waitFor();
  record('settings shortcut opens the simple model picker without model execution');
}
